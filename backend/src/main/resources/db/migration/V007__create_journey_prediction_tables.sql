CREATE TABLE traveler_profile (
    id UUID PRIMARY KEY,
    anonymous_key UUID NOT NULL UNIQUE,
    slow_walk_speed_mps NUMERIC(4, 2) NOT NULL DEFAULT 0.90,
    walk_speed_mps NUMERIC(4, 2) NOT NULL DEFAULT 1.30,
    fast_walk_speed_mps NUMERIC(4, 2) NOT NULL DEFAULT 1.70,
    run_speed_mps NUMERIC(4, 2) NOT NULL DEFAULT 2.50,
    sample_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_traveler_profile_speed_range CHECK (
        slow_walk_speed_mps BETWEEN 0.30 AND 6.00
        AND walk_speed_mps BETWEEN 0.30 AND 6.00
        AND fast_walk_speed_mps BETWEEN 0.30 AND 6.00
        AND run_speed_mps BETWEEN 0.30 AND 6.00
    ),
    CONSTRAINT ck_traveler_profile_speed_order CHECK (
        slow_walk_speed_mps <= walk_speed_mps
        AND walk_speed_mps <= fast_walk_speed_mps
        AND fast_walk_speed_mps <= run_speed_mps
    ),
    CONSTRAINT ck_traveler_profile_sample_count CHECK (sample_count >= 0)
);

CREATE TABLE journey_session (
    id UUID PRIMARY KEY,
    traveler_profile_id UUID REFERENCES traveler_profile (id) ON DELETE SET NULL,
    line_id UUID NOT NULL REFERENCES transit_line (id),
    direction_id UUID NOT NULL REFERENCES route_direction (id),
    boarding_stop_id UUID NOT NULL REFERENCES transit_stop (id),
    alighting_stop_id UUID REFERENCES transit_stop (id),
    target_probability NUMERIC(5, 4) NOT NULL DEFAULT 0.8000,
    desired_arrival_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_journey_target_probability CHECK (
        target_probability > 0 AND target_probability <= 1
    ),
    CONSTRAINT ck_journey_status CHECK (
        status IN ('ACTIVE', 'COMPLETED', 'CANCELLED', 'EXPIRED')
    ),
    CONSTRAINT ck_journey_distinct_stops CHECK (
        alighting_stop_id IS NULL OR boarding_stop_id <> alighting_stop_id
    ),
    CONSTRAINT ck_journey_expiry CHECK (expires_at > created_at)
);

CREATE TABLE traveler_location_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_id UUID NOT NULL REFERENCES journey_session (id) ON DELETE CASCADE,
    latitude NUMERIC(9, 6) NOT NULL,
    longitude NUMERIC(9, 6) NOT NULL,
    accuracy_m NUMERIC(8, 2) NOT NULL,
    speed_mps NUMERIC(6, 2),
    observed_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_traveler_location_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_traveler_location_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_traveler_location_accuracy CHECK (accuracy_m >= 0),
    CONSTRAINT ck_traveler_location_speed CHECK (speed_mps IS NULL OR speed_mps >= 0),
    CONSTRAINT ck_traveler_location_expiry CHECK (expires_at >= received_at)
);

CREATE TABLE boarding_prediction_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calculation_id UUID NOT NULL,
    journey_id UUID NOT NULL REFERENCES journey_session (id) ON DELETE CASCADE,
    location_observation_id BIGINT REFERENCES traveler_location_observation (id) ON DELETE SET NULL,
    vehicle_run_observation_id BIGINT REFERENCES vehicle_run_observation (id) ON DELETE SET NULL,
    arrival_prediction_observation_id BIGINT REFERENCES arrival_prediction_observation (id) ON DELETE SET NULL,
    provider_vehicle_id VARCHAR(100) NOT NULL,
    pace_type VARCHAR(20) NOT NULL,
    pace_speed_mps NUMERIC(6, 2) NOT NULL,
    distance_m NUMERIC(10, 2) NOT NULL,
    user_expected_at TIMESTAMPTZ NOT NULL,
    user_min_expected_at TIMESTAMPTZ NOT NULL,
    user_max_expected_at TIMESTAMPTZ NOT NULL,
    vehicle_expected_at TIMESTAMPTZ NOT NULL,
    vehicle_min_expected_at TIMESTAMPTZ NOT NULL,
    vehicle_max_expected_at TIMESTAMPTZ NOT NULL,
    boarding_probability NUMERIC(6, 5) NOT NULL,
    decision VARCHAR(30) NOT NULL,
    recommended BOOLEAN NOT NULL DEFAULT FALSE,
    confidence VARCHAR(20) NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    factors JSONB NOT NULL DEFAULT '{}'::JSONB,
    calculated_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_boarding_prediction_pace CHECK (
        pace_type IN ('SLOW_WALK', 'WALK', 'FAST_WALK', 'RUN')
    ),
    CONSTRAINT ck_boarding_prediction_pace_speed CHECK (pace_speed_mps > 0),
    CONSTRAINT ck_boarding_prediction_distance CHECK (distance_m >= 0),
    CONSTRAINT ck_boarding_prediction_user_range CHECK (
        user_min_expected_at <= user_expected_at
        AND user_expected_at <= user_max_expected_at
    ),
    CONSTRAINT ck_boarding_prediction_vehicle_range CHECK (
        vehicle_min_expected_at <= vehicle_expected_at
        AND vehicle_expected_at <= vehicle_max_expected_at
    ),
    CONSTRAINT ck_boarding_prediction_probability CHECK (
        boarding_probability BETWEEN 0 AND 1
    ),
    CONSTRAINT ck_boarding_prediction_decision CHECK (
        decision IN ('COMFORTABLE', 'LEAVE_NOW', 'HURRY', 'UNLIKELY', 'INSUFFICIENT_DATA')
    ),
    CONSTRAINT ck_boarding_prediction_confidence CHECK (
        confidence IN ('HIGH', 'MEDIUM', 'LOW', 'UNKNOWN')
    ),
    CONSTRAINT ck_boarding_prediction_expiry CHECK (expires_at >= calculated_at),
    CONSTRAINT uq_boarding_prediction_calculation_vehicle_pace UNIQUE (
        calculation_id, provider_vehicle_id, pace_type
    )
);

CREATE INDEX ix_journey_session_profile_status
    ON journey_session (traveler_profile_id, status, updated_at DESC);

CREATE INDEX ix_journey_session_line_status
    ON journey_session (line_id, status, updated_at DESC);

CREATE INDEX ix_journey_session_expiry
    ON journey_session (expires_at)
    WHERE status = 'ACTIVE';

CREATE INDEX ix_traveler_location_journey_time
    ON traveler_location_observation (journey_id, observed_at DESC, received_at DESC);

CREATE INDEX ix_traveler_location_expiry
    ON traveler_location_observation (expires_at);

CREATE INDEX ix_boarding_prediction_journey_time
    ON boarding_prediction_snapshot (journey_id, calculated_at DESC, id DESC);

CREATE INDEX ix_boarding_prediction_calculation
    ON boarding_prediction_snapshot (calculation_id, provider_vehicle_id, pace_type);

CREATE INDEX ix_boarding_prediction_expiry
    ON boarding_prediction_snapshot (expires_at);

CREATE INDEX ix_transit_stop_coordinates
    ON transit_stop (latitude, longitude)
    WHERE latitude IS NOT NULL AND longitude IS NOT NULL;

COMMENT ON COLUMN traveler_profile.anonymous_key IS
    'Client-generated pseudonymous key. It must not contain account or device identifiers.';

COMMENT ON TABLE traveler_location_observation IS
    'Short-lived user location samples. Retention cleanup is required.';

COMMENT ON COLUMN boarding_prediction_snapshot.factors IS
    'Non-secret, versioned inputs and reason codes used to explain and reproduce the prediction.';
